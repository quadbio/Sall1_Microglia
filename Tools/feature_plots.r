dotplot <- function(exprmat, genes, cl,
                    gene.reorder=TRUE, specified.order=NULL, cl.reorder.by.hc=TRUE, max.diag=TRUE,
                    emphasize_genes = NULL, emphasize_cl = NULL,
                    colors=c("#d9d9d9", "#252525"), point.size.factor=3.5, plot.margin=NULL, plot.cex=1.2, col.space.factor=1, row.space.factor=1, verbose = F){
  
  genes <- intersect(genes, rownames(exprmat))
  expr <- as.matrix(sapply(unique(cl), function(x) rowMeans(exprmat[genes, which(cl == x)])))
  rownames(expr) <- genes
  colnames(expr) <- unique(cl)
  expr <- expr[which(apply(expr, 1, sd)>0),]
  prop <- sapply(unique(cl), function(x) rowMeans(exprmat[rownames(expr), which(cl == x)] > 0))
  colnames(prop) <- unique(cl)
  
  if(gene.reorder){
    if (verbose)
      cat("Reorder genes based on hierarchical clustering\n")
    hc.gene <- hclust(as.dist(1-cor(t(expr))))
    gene.order = hc.gene$order
  }else{
    if (verbose)
      cat("No reordering for genes\n")
    gene.order <- rownames(expr)
  }
  expr <- expr[gene.order,] 
  if(!is.null(specified.order)){
    cat("Reorder clusters according to user provided order\n")
    expr <- expr[,specified.order]
  }else{
    if(cl.reorder.by.hc){
      if (verbose)
        cat("Reorder clusters based on hierarchical clustering of provided expression matrix\n")
      hc <- hclust(as.dist(1-cor(expr)))
      expr <- expr[,hc$order]
    }else{
      if (verbose)
        cat("Do not reorder clusters\n")
      expr <- expr
    }
  }
  if(max.diag){
    max.cl.idx <- colnames(expr)[apply(expr, 1, which.max)]
    idx <- unlist(lapply(colnames(expr), function(i){
      which(max.cl.idx==i)
    }))
    expr <- expr[idx,]
  }
  prop <- prop[rownames(expr),colnames(expr)]
  
  scale.cl.expr <- t(scale(t(expr)))
  scale.cl.expr <- rbind(scale.cl.expr, rep(c(-1,1), c(ncol(scale.cl.expr)-4,4)))
  colorPal <- grDevices::colorRampPalette(colors)
  color.break.num <- 30
  cellColor <- as.vector(t(apply(scale.cl.expr, 1, function(values){
    adjustcolor(colorPal(color.break.num), alpha=.8)[as.numeric(cut(values, breaks=color.break.num, right=F, include.lowest=T))]
  })))
  cl.num <- ncol(expr)
  
  new.vec <- rep(0, ncol(prop))
  new.vec[ncol(prop)-0:3] <- seq(from=1,to=0.25,length=4)
  prop <- rbind(prop, new.vec)
  point.size <- as.vector(prop)*point.size.factor
  g1 <- c(rownames(expr), "")
  
  par(xpd=TRUE)
  if (! is.null(plot.margin))
    par(mar = plot.margin)
  plot(c(1, length(g1)), c(1, cl.num), type="n", bty="n", xaxt="n", yaxt="n", xlab="", ylab="")
  points(rep(seq(length(g1))*col.space.factor, cl.num), rep(seq(cl.num)*row.space.factor, each=length(g1)), pch=16, col=cellColor, cex=point.size)
  
  font_col <- rep(1, length(g1))
  size_col <- rep(plot.cex, length(g1))
  if (!is.null(emphasize_genes)){
    font_col[g1 %in% emphasize_genes] <- 2
    size_col[g1 %in% emphasize_genes] <- plot.cex * 1.1
  }
  mtext(g1, side=1, at=seq(length(g1))*col.space.factor, las=2, cex = size_col, font = font_col)
  
  font_row <- rep(1, ncol(expr))
  size_row <- rep(plot.cex, ncol(expr))
  if (!is.null(emphasize_cl)){
    font_row[colnames(expr) %in% emphasize_cl] <- 2
    size_row[colnames(expr) %in% emphasize_cl] <- plot.cex * 1.1
  }
  mtext(sub("Cluster_", "", colnames(expr)), side=2, at=seq(cl.num)*row.space.factor, las=1, cex = size_row, font = font_row)
  
  text(rep((length(g1)+2)*col.space.factor, 4)+0.5, cl.num-3:0, labels=c(0.25,0.5,0.75,1), cex=plot.cex, pos=4)
}


# stacked violing plot function

library(Seurat)
library(ggplot2)

## remove the x-axis text and tick 
## plot.margin to adjust the white space between each plot.
## ... pass any arguments to VlnPlot in Seurat
modify_vlnplot<- function(obj, 
                          feature, 
                          pt.size = 0,
                          plot.margin = margin(0, 0, 0, 0, "cm"),
                          ...) {
  p<- VlnPlot(obj, features = feature, pt.size = pt.size, ... )+
    ylab(feature) + 
    theme(legend.position = "none",
          plot.title= element_blank(),
          axis.title.x = element_blank(),
          axis.text.x = element_blank(), 
          axis.ticks.x = element_blank(), 
          axis.title.y = element_text(size = rel(1), angle = 0), 
          axis.text.y = element_text(size = rel(1)), 
          plot.margin = plot.margin ) 
  return(p)
}


## extract the max value of the y axis
extract_max<- function(p){
  ymax<- max(ggplot_build(p)$layout$panel_scales_y[[1]]$range$range)
  return(ceiling(ymax))
}


## main function
StackedVlnPlot<- function(obj, features,
                          pt.size = 0, 
                          plot.margin = unit(c(-0.75, 0, -0.75, 0), "cm"),
                          ...) {
  
  plot_list<- purrr::map(features, function(x) modify_vlnplot(obj = obj,feature = x, ...))
  
  # Add back x-axis title to bottom plot. patchwork is going to support this?
  plot_list[[length(plot_list)]]<- plot_list[[length(plot_list)]] +
    theme(axis.text.x=element_text(angle = 45, hjust = 1, vjust = 1), 
          axis.ticks.x = element_line())
  
  # change the y-axis tick to only max value 
  ymaxs<- purrr::map_dbl(plot_list, extract_max)
  plot_list<- purrr::map2(plot_list, ymaxs, function(x,y) x + 
                            scale_y_continuous(breaks = c(y)) + 
                            expand_limits(y = y))
  
  p<- patchwork::wrap_plots(plotlist = plot_list, ncol = 1)
  return(p)
}



# Add graph to the base R graphics plot
draw_graph <- function(layout, graph, lwd = 0.2, col = "grey") {
  res <- rep(x = 1:(length(graph@p) - 1), times = (graph@p[-1] - graph@p[-length(graph@p)]))
  segments(x0 = layout[graph@i + 1, 1], x1 = layout[res, 1], y0 = layout[graph@i +
                                                                           1, 2], y1 = layout[res, 2], lwd = lwd, col = col)
}

